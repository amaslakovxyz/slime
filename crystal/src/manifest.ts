// The Crystal folder: manifest.json, one module per handler, and a generated index.
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { SERVICES_FILE, SERVICES_TYPES_FILE, renderServiceTypes, renderServices } from './services.js';
import type { HandlerProvenance, ParamTypes, ReviewStatus, Shape } from '@slime-cloud/core';

export interface ManifestEntry {
  file: string;
  sha256: string;
  intent: string;
  output: Shape;
  paramTypes: ParamTypes;
  schemaHash: string;
  review: ReviewStatus;
  isOptimized: boolean;
  notes: string[];
  /** The Liquid handler it came from. */
  provenance: HandlerProvenance;
  createdAt: string;
  /** Its function name in services.mjs; set once, so a rename never breaks the app. */
  service?: string;
  /** The reference `verify` compares it with (cases.ts), and that file's pinned hash. */
  cases?: string;
  casesSha256?: string;
  /** The API sources a steps Crystal calls: its service then takes the app's sources, not only the connector. */
  sources?: string[];
}

export interface Manifest {
  version: typeof MANIFEST_VERSION;
  /** Keyed by request key. */
  entries: Record<string, ManifestEntry>;
}

export const MANIFEST_FILE = 'manifest.json';
export const INDEX_FILE = 'index.mjs';
export const INDEX_TYPES_FILE = 'index.d.mts';
export const MODULE_EXTENSION = '.mjs';
const MANIFEST_VERSION = 1;
const INDEX_HEADER = '// Generated by crystallize (@slime-cloud/crystal). Do not edit: `slime-crystal check` compares it with manifest.json.\n';

export function moduleFileFor(key: string): string {
  return `${key}${MODULE_EXTENSION}`;
}

export async function readManifest(dir: string): Promise<Manifest> {
  const json = await readFile(join(dir, MANIFEST_FILE), 'utf8').catch((error: NodeJS.ErrnoException) => {
    if (error.code === 'ENOENT') return undefined;
    throw error;
  });
  return json === undefined ? { version: MANIFEST_VERSION, entries: {} } : parseManifest(json);
}

/** The manifest from its text, wherever it is stored. */
export function parseManifest(json: string): Manifest {
  const manifest = JSON.parse(json) as Manifest;
  if (manifest.version !== MANIFEST_VERSION) throw new Error(`${MANIFEST_FILE}: unsupported version ${String(manifest.version)}`);
  return manifest;
}

/** Writes the manifest and the index generated from it; sorted, so diffs stay small. */
export async function writeManifestAndIndex(dir: string, manifest: Manifest): Promise<void> {
  await mkdir(dir, { recursive: true });
  await writeFile(join(dir, MANIFEST_FILE), renderManifest(manifest));
  await writeFile(join(dir, INDEX_FILE), renderIndex(manifest));
  await writeFile(join(dir, INDEX_TYPES_FILE), renderIndexTypes());
  await writeFile(join(dir, SERVICES_FILE), renderServices(manifest));
  await writeFile(join(dir, SERVICES_TYPES_FILE), renderServiceTypes(manifest));
}

export function renderManifest({ entries }: Manifest): string {
  return `${JSON.stringify({ version: MANIFEST_VERSION, entries: sortedEntries(entries) }, null, 2)}\n`;
}

/** The registry the app passes as `crystal` in SlimeConfig (C10). */
export function renderIndex({ entries }: Manifest): string {
  const keys = Object.keys(sortedEntries(entries));
  const imports = keys.map((key, index) => `import * as crystal${index} from './${entries[key]!.file}';`);
  const registryEntries = keys.map((key, index) => `  ${JSON.stringify(key)}: Object.freeze({ ...crystal${index}, ...${JSON.stringify(indexMetadata(entries[key]!))} }),`);
  return `${INDEX_HEADER}${imports.join('\n')}${imports.length > 0 ? '\n\n' : ''}export const crystals = Object.freeze({\n${registryEntries.join('\n')}${registryEntries.length > 0 ? '\n' : ''}});\n`;
}

export function renderIndexTypes(): string {
  return `${INDEX_HEADER}import type { CrystalRegistry } from '@slime-cloud/core';\n\nexport declare const crystals: CrystalRegistry;\n`;
}

function indexMetadata({ intent, output, paramTypes, schemaHash, review }: ManifestEntry): Record<string, unknown> {
  return { intent, output, paramTypes, schemaHash, review };
}

function sortedEntries(entries: Record<string, ManifestEntry>): Record<string, ManifestEntry> {
  return Object.fromEntries(Object.keys(entries).sort().map((key) => [key, entries[key]!]));
}
