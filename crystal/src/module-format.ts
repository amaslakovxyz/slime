// One Crystal module, in one of two forms, nothing else in it:
//   - one query:  `sql`, `params` and `shape(rows, input)` (or `shape = null`);
//   - steps:      `steps` (SQL and API steps, as the Liquid handler had them) and
//                 `shape(data, input)` (or `shape = null` with a single step).
// `steps` is a plain literal: strings, numbers, booleans, null, arrays and objects only.
import type { ExportNamedDeclaration, Expression, ModuleDeclaration, Statement } from 'acorn';
import type { ApiArg, Step } from '@slime-cloud/core';
import { CrystalCodeError, checkShapeFunction, parseModuleSource } from './allowlist.js';

export interface QueryCode {
  sql: string;
  params: string[];
  /** Source of `function shape(rows, input) { ... }`, or null when SQL rows are the output. */
  shape: string | null;
}

export interface StepsCode {
  steps: Step[];
  /** Source of `function shape(data, input) { ... }`, or null with a single step whose rows are the output. */
  shape: string | null;
}

export type CrystalCode = QueryCode | StepsCode;

/** One read-only statement a Crystal runs, for the SQL lint and the cost check. */
export interface SqlStatement {
  sql: string;
  params: string[];
}

const MODULE_HEADER =
  '// Generated by crystallize (@slime-cloud/crystal). Do not edit: manifest.json pins this\n' +
  "// file's hash, and `slime-crystal check` refuses a file that doesn't match it.\n";
const QUERY_EXPORTS = 3;
const STEPS_EXPORTS = 2;
const STEP_NAME = /^[A-Za-z_][A-Za-z0-9_]*$/;
const SQL_STEP_KEYS = ['name', 'params', 'source', 'sql'];
const API_STEP_KEYS = ['args', 'name', 'operation', 'source'];
const ARG_KEYS = ['input', 'param', 'value'];

export function isStepsCode(code: CrystalCode): code is StepsCode {
  return 'steps' in code;
}

/** Every SQL statement the module runs. */
export function sqlStatementsOf(code: CrystalCode): SqlStatement[] {
  if (!isStepsCode(code)) return [{ sql: code.sql, params: code.params }];
  return code.steps.flatMap((step) => ('sql' in step ? [{ sql: step.sql, params: step.params }] : []));
}

/** Every input name the module reads: SQL params and API arguments taken from input. */
export function inputNamesOf(code: CrystalCode): string[] {
  if (!isStepsCode(code)) return code.params;
  return code.steps.flatMap((step) => ('sql' in step ? step.params : step.args.flatMap(({ input }) => (input === null ? [] : [input]))));
}

/** The API sources a module calls, by name. */
export function apiSourcesOf(code: CrystalCode): string[] {
  if (!isStepsCode(code)) return [];
  return [...new Set(code.steps.flatMap((step) => ('operation' in step ? [step.source] : [])))].sort();
}

// Trailing whitespace is stripped so pre-commit hooks never rewrite the file and break its pinned hash.
export function renderModule(code: CrystalCode): string {
  const shapeExport = code.shape ? `export ${code.shape.trim().split('\n').map((line) => line.trimEnd()).join('\n')}` : 'export const shape = null;';
  const data = isStepsCode(code)
    ? `export const steps = ${JSON.stringify(code.steps.map(canonicalStep), null, 2)};\n`
    : `export const sql = ${JSON.stringify(code.sql)};\nexport const params = ${JSON.stringify(code.params)};\n`;
  return `${MODULE_HEADER}${data}${shapeExport}\n`;
}

/** Exactly the keys a step has, in one order, whatever the stored artifact carried. */
function canonicalStep(step: Step): Step {
  if ('sql' in step) return { name: step.name, source: step.source, sql: step.sql, params: [...step.params] };
  return { name: step.name, source: step.source, operation: step.operation, args: step.args.map(({ param, input, value }) => ({ param, input, value })) };
}

/** Parses a module, checks its structure and runs the allowlist on its shape function. */
export function parseModule(source: string): CrystalCode {
  const { body } = parseModuleSource(source);
  if (body.length === STEPS_EXPORTS && constExport(body[0], 'steps')) {
    const steps = stepsLiteral(body[0]);
    const shape = shapeSource(body[1], source);
    if (shape === null && steps.length !== 1) throw new CrystalCodeError('`shape` may be null only with a single step');
    return { steps, shape };
  }
  if (body.length !== QUERY_EXPORTS) throw new CrystalCodeError('module must contain exactly the sql, params and shape exports, or the steps and shape exports');
  const [sqlExport, paramsExport, shapeExport] = body;
  return { sql: sqlLiteral(sqlExport), params: paramsLiteral(paramsExport), shape: shapeSource(shapeExport, source) };
}

function sqlLiteral(statement: Statement | ModuleDeclaration | undefined): string {
  const value = constExport(statement, 'sql');
  if (value?.type !== 'Literal' || typeof value.value !== 'string') throw new CrystalCodeError('`sql` must be a string literal');
  return value.value;
}

function paramsLiteral(statement: Statement | ModuleDeclaration | undefined): string[] {
  const value = constExport(statement, 'params');
  if (value?.type !== 'ArrayExpression') throw new CrystalCodeError('`params` must be an array of string literals');
  return value.elements.map((element) => {
    if (element?.type !== 'Literal' || typeof element.value !== 'string') throw new CrystalCodeError('`params` must be an array of string literals');
    return element.value;
  });
}

function stepsLiteral(statement: Statement | ModuleDeclaration | undefined): Step[] {
  const steps = plainValue(constExport(statement, 'steps')!);
  if (!Array.isArray(steps) || steps.length === 0) throw new CrystalCodeError('`steps` must be a non-empty array of steps');
  const names = new Set<string>();
  return steps.map((step, index) => {
    const checked = checkedStep(step, index);
    if (names.has(checked.name)) throw new CrystalCodeError(`step name "${checked.name}" is used twice`);
    names.add(checked.name);
    return checked;
  });
}

function checkedStep(step: unknown, index: number): Step {
  const where = `steps[${index}]`;
  if (!isRecord(step)) throw new CrystalCodeError(`${where} must be an object`);
  if (typeof step['name'] !== 'string' || !STEP_NAME.test(step['name'])) throw new CrystalCodeError(`${where}.name must be an identifier`);
  if (typeof step['source'] !== 'string' || step['source'] === '') throw new CrystalCodeError(`${where}.source must be a source name`);
  if ('sql' in step) {
    assertKeys(step, SQL_STEP_KEYS, where);
    if (typeof step['sql'] !== 'string') throw new CrystalCodeError(`${where}.sql must be a string`);
    if (!isStringArray(step['params'])) throw new CrystalCodeError(`${where}.params must be an array of input names`);
    return { name: step['name'], source: step['source'], sql: step['sql'], params: step['params'] };
  }
  assertKeys(step, API_STEP_KEYS, where);
  if (typeof step['operation'] !== 'string' || step['operation'] === '') throw new CrystalCodeError(`${where}.operation must be an operation name`);
  if (!Array.isArray(step['args'])) throw new CrystalCodeError(`${where}.args must be an array`);
  const args = step['args'].map((arg, argIndex) => checkedArg(arg, `${where}.args[${argIndex}]`));
  return { name: step['name'], source: step['source'], operation: step['operation'], args };
}

/** Exactly one of `input` and `value` is non-null, as lint requires of Liquid (MS4). */
function checkedArg(arg: unknown, where: string): ApiArg {
  if (!isRecord(arg)) throw new CrystalCodeError(`${where} must be an object`);
  assertKeys(arg, ARG_KEYS, where);
  const { param, input, value } = arg;
  if (typeof param !== 'string' || param === '') throw new CrystalCodeError(`${where}.param must be a param name`);
  if (input !== null && typeof input !== 'string') throw new CrystalCodeError(`${where}.input must be an input name or null`);
  if (value !== null && !['string', 'number', 'boolean'].includes(typeof value)) throw new CrystalCodeError(`${where}.value must be a string, number, boolean or null`);
  if ((input === null) === (value === null)) throw new CrystalCodeError(`${where}: exactly one of input and value must be non-null`);
  return { param, input, value: value as ApiArg['value'] };
}

function assertKeys(object: Record<string, unknown>, expected: readonly string[], where: string): void {
  const keys = Object.keys(object).sort();
  if (keys.join() !== expected.join()) throw new CrystalCodeError(`${where} must have exactly the keys ${expected.join(', ')}`);
}

/** A literal's value: strings, numbers, booleans, null, arrays and objects with plain keys; nothing that runs. */
function plainValue(node: Expression): unknown {
  if (node.type === 'Literal' && (node.value === null || ['string', 'number', 'boolean'].includes(typeof node.value)) && !('regex' in node)) return node.value;
  if (node.type === 'UnaryExpression' && node.operator === '-' && node.argument.type === 'Literal' && typeof node.argument.value === 'number') return -node.argument.value;
  if (node.type === 'ArrayExpression') {
    return node.elements.map((element) => {
      if (!element || element.type === 'SpreadElement') throw new CrystalCodeError('`steps` may hold only plain values (no holes or spreads)');
      return plainValue(element);
    });
  }
  if (node.type === 'ObjectExpression') {
    const object: Record<string, unknown> = {};
    for (const property of node.properties) {
      if (property.type !== 'Property' || property.computed || property.method || property.shorthand || property.kind !== 'init') {
        throw new CrystalCodeError('`steps` may hold only plain values (no spreads, methods, getters or computed keys)');
      }
      const key = property.key.type === 'Identifier' ? property.key.name : property.key.type === 'Literal' ? String(property.key.value) : undefined;
      if (key === undefined || key === '__proto__') throw new CrystalCodeError('`steps` has a key that is not allowed');
      object[key] = plainValue(property.value as Expression);
    }
    return object;
  }
  throw new CrystalCodeError(`\`steps\` may hold only plain values, not ${node.type} (at offset ${node.start})`);
}

function isRecord(value: unknown): value is Record<string, unknown> {
  return typeof value === 'object' && value !== null && !Array.isArray(value);
}

function isStringArray(value: unknown): value is string[] {
  return Array.isArray(value) && value.every((item) => typeof item === 'string');
}

function shapeSource(statement: Statement | ModuleDeclaration | undefined, source: string): string | null {
  const nullShape = constExport(statement, 'shape');
  if (nullShape) {
    if (nullShape.type === 'Literal' && nullShape.value === null) return null;
    throw new CrystalCodeError('`shape` must be a function or null');
  }
  const declaration = statement?.type === 'ExportNamedDeclaration' ? statement.declaration : undefined;
  if (declaration?.type !== 'FunctionDeclaration' || declaration.id.name !== 'shape') {
    throw new CrystalCodeError('the last export must be `export function shape(...)` or `export const shape = null`');
  }
  checkShapeFunction(declaration);
  return source.slice(declaration.start, declaration.end);
}

function constExport(statement: Statement | ModuleDeclaration | undefined, name: string): Expression | undefined {
  if (statement?.type !== 'ExportNamedDeclaration') return undefined;
  const { declaration } = statement as ExportNamedDeclaration;
  if (declaration?.type !== 'VariableDeclaration' || declaration.kind !== 'const' || declaration.declarations.length !== 1) return undefined;
  const [declarator] = declaration.declarations;
  return declarator?.id.type === 'Identifier' && declarator.id.name === name ? (declarator.init ?? undefined) : undefined;
}
