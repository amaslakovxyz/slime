// Crystals in S3: loading modules as data (SHA-256 against the manifest, then
// parseModule), publishing modules before a conditional manifest, removing every
// version, and the whole cloud Crystallize on one instance.
import './setup.js';
import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { mkdtemp, readFile, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { after, describe, test } from 'node:test';
import { PutObjectCommand } from '@aws-sdk/client-s3';
import type { Manifest, ManifestEntry } from '@slime-cloud/crystal';
import { CrystallizeConflictError, S3CrystalStore } from '../src/crystal-store.js';
import { FakeS3 } from './fake-s3.js';
import { BUCKET, harness, isDatabaseAvailable, keyOf, type Harness } from './tenant-harness.js';

const ID = 'ep-00000000a1';
const PREFIX = `endpoints/${ID}/crystal/`;
const KEY_1 = 'a'.repeat(64);
const KEY_2 = 'b'.repeat(64);
const SHAPE = 'function shape(rows) {\n  return rows.map((r) => ({ plan: r.plan }));\n}';
const MODULE = `// Generated by crystallize.\nexport const sql = "SELECT p.name AS plan FROM plans p WHERE $1::text IS NOT NULL";\nexport const params = ["country"];\nexport ${SHAPE}\n`;

const workRoots: string[] = [];
after(() => Promise.all(workRoots.map((dir) => rm(dir, { recursive: true, force: true }))));

function sha256(text: string): string {
  return createHash('sha256').update(text).digest('hex');
}

function entryFor(key: string, text: string): ManifestEntry {
  return {
    file: `${key}.mjs`,
    sha256: sha256(text),
    intent: `plans, ${key.slice(0, 1)}`,
    output: [{ plan: 'string' }],
    paramTypes: { country: 'string' },
    schemaHash: 'schema',
    review: 'none',
    isOptimized: false,
    notes: [],
    provenance: { schemaHash: 'schema', dictionaryHash: 'd', promptHash: 'p', model: 'm' },
    createdAt: '2026-11-21T00:00:00.000Z',
  };
}

function manifestText(entries: Record<string, ManifestEntry>): string {
  return JSON.stringify({ version: 1, entries } satisfies Manifest);
}

async function storeOver(s3: FakeS3): Promise<S3CrystalStore> {
  const workRoot = await mkdtemp(join(tmpdir(), 'slime-crystal-store-test-'));
  workRoots.push(workRoot);
  return new S3CrystalStore({ bucket: BUCKET, client: s3, workRoot });
}

/** Stores modules and their manifest as a previous Crystallize left them. */
async function seed(s3: FakeS3, modules: Record<string, string>, entries: Record<string, ManifestEntry> = {}): Promise<void> {
  for (const [key, text] of Object.entries(modules)) {
    await s3.send(new PutObjectCommand({ Bucket: BUCKET, Key: `${PREFIX}${key}.mjs`, Body: text }));
    entries[key] ??= entryFor(key, text);
  }
  await s3.send(new PutObjectCommand({ Bucket: BUCKET, Key: `${PREFIX}manifest.json`, Body: manifestText(entries) }));
  s3.puts.length = 0;
}

describe('S3CrystalStore', () => {
  test('load builds handlers whose shape is the module source, with the manifest metadata', async () => {
    const s3 = new FakeS3();
    await seed(s3, { [KEY_1]: MODULE });
    const store = await storeOver(s3);
    const { registry, etag, warnings } = await store.load(ID);
    assert.deepEqual(warnings, []);
    assert.equal(etag, await store.version(ID));
    const crystal = registry[KEY_1];
    assert.equal(crystal?.shape, SHAPE);
    assert.ok(crystal && 'params' in crystal);
    assert.deepEqual([crystal.params, crystal.intent, crystal.paramTypes, crystal.review], [['country'], `plans, a`, { country: 'string' }, 'none']);
  });

  test('load builds a steps Crystal (SQL and API steps) the same way, its shape as source', async () => {
    const steps = [
      { name: 'plans', source: 'db', sql: 'SELECT name AS plan FROM plans WHERE $1::text IS NOT NULL', params: ['country'] },
      { name: 'feedback', source: 'notion', operation: 'feedback.query', args: [{ param: 'sentiment', input: null, value: 'negative' }] },
    ];
    const shape = 'function shape(data) {\n  return data.plans.map((p) => ({ plan: p.plan }));\n}';
    const text = `// Generated by crystallize.\nexport const steps = ${JSON.stringify(steps, null, 2)};\nexport ${shape}\n`;
    const s3 = new FakeS3();
    await seed(s3, { [KEY_1]: text });
    const { registry, warnings } = await (await storeOver(s3)).load(ID);
    assert.deepEqual(warnings, []);
    const crystal = registry[KEY_1];
    assert.ok(crystal && 'steps' in crystal);
    assert.deepEqual([crystal.steps, crystal.shape], [steps, shape]);
  });

  test('a module that does not match its SHA-256, or fails the module check, is dropped with a warning', async () => {
    const s3 = new FakeS3();
    const tampered = MODULE.replace('r.plan', 'process.env');
    const notAModule = 'export const sql = "SELECT 1";\n';
    await seed(s3, { [KEY_1]: tampered, [KEY_2]: notAModule, ['c'.repeat(64)]: MODULE }, { [KEY_1]: entryFor(KEY_1, MODULE) });
    const { registry, warnings } = await (await storeOver(s3)).load(ID);
    assert.deepEqual(Object.keys(registry), ['c'.repeat(64)]);
    assert.equal(warnings.length, 2);
    assert.match(warnings.find((w) => w.includes(KEY_1)) ?? '', /does not match the SHA-256/);
    assert.match(warnings.find((w) => w.includes(KEY_2)) ?? '', /failed the module check/);
  });

  test('an endpoint with no manifest has no Crystals and no version', async () => {
    const store = await storeOver(new FakeS3());
    assert.deepEqual(await store.load(ID), { registry: {}, warnings: [] });
    assert.equal(await store.version(ID), undefined);
  });

  test('publish puts only the new modules, then the manifest on condition of the version the work started from', async () => {
    const s3 = new FakeS3();
    await seed(s3, { [KEY_1]: MODULE });
    const store = await storeOver(s3);
    const before = await store.version(ID);
    const work = await store.prepareWork(ID);
    assert.deepEqual([work.etag, work.stored], [before, [KEY_1]]);
    assert.equal(await readFile(join(work.dir, `${KEY_1}.mjs`), 'utf8'), MODULE);

    // What crystallize() leaves in the folder: one more module, and the manifest naming both.
    const second = MODULE.replace('plan: r.plan', 'name: r.plan');
    await writeFile(join(work.dir, `${KEY_2}.mjs`), second);
    await writeFile(join(work.dir, 'manifest.json'), manifestText({ [KEY_1]: entryFor(KEY_1, MODULE), [KEY_2]: entryFor(KEY_2, second) }));
    const etag = await store.publish(ID, work);

    assert.deepEqual(s3.puts, [{ key: `${PREFIX}${KEY_2}.mjs` }, { key: `${PREFIX}manifest.json`, ifMatch: before }]);
    assert.equal(etag, await store.version(ID));
    assert.deepEqual(Object.keys((await store.load(ID)).registry).sort(), [KEY_1, KEY_2]);
    await store.discardWork(work);
    await assert.rejects(readFile(join(work.dir, 'manifest.json')), /ENOENT/);
  });

  test('a Crystallize that started from an older manifest, or from none when one appeared, loses with CrystallizeConflictError', async () => {
    const s3 = new FakeS3();
    const store = await storeOver(s3);
    const first = await store.prepareWork(ID);
    const second = await store.prepareWork(ID);
    for (const work of [first, second]) {
      await writeFile(join(work.dir, `${KEY_1}.mjs`), MODULE);
      await writeFile(join(work.dir, 'manifest.json'), manifestText({ [KEY_1]: entryFor(KEY_1, MODULE) }));
    }
    await store.publish(ID, first);
    assert.equal(s3.puts.at(-1)?.ifNoneMatch, '*');
    await assert.rejects(store.publish(ID, second), CrystallizeConflictError);

    const third = await store.prepareWork(ID);
    const fourth = await store.prepareWork(ID);
    for (const work of [third, fourth]) await writeFile(join(work.dir, 'manifest.json'), manifestText({ [KEY_1]: entryFor(KEY_1, MODULE) }));
    await store.publish(ID, third);
    await assert.rejects(store.publish(ID, fourth), (error: unknown) => error instanceof CrystallizeConflictError && /try again/.test(error.message));
  });
});

const hasDatabase = await isDatabaseAvailable();

const PLANS_IN_COUNTRY = {
  intent: 'plans that have accounts in a given country, each with the list of those account names',
  input: { country: 'DE' },
  output: [{ plan: 'string', accounts: [{ name: 'string' }] }],
};

/** 12 runs of a request with a shape: Liquid after 3 (canned handlers, no reviewer), ready to crystallize after 10. */
async function liquidHandler(h: Harness): Promise<{ key: string; answer: unknown }> {
  let answer: unknown;
  let key = '';
  for (let run = 0; run < 12; run++) {
    const { status, json } = await h.call(`/ep/${ID}/v0/query`, { key: keyOf(ID), body: PLANS_IN_COUNTRY });
    assert.equal(status, 200);
    answer = json?.data;
    key = json?.meta?.handlerKey ?? '';
  }
  return { key, answer };
}

describe('cloud Crystallize on one instance', { skip: !hasDatabase && 'demo Postgres is down' }, () => {
  test('a Liquid handler with 10 runs crystallizes into S3, and the same instance answers its Crystal route at once', async () => {
    const h = await harness();
    try {
      h.addEndpoint(ID);
      const { key, answer } = await liquidHandler(h);

      const { status, json } = await h.call(`/ep/${ID}/v0/crystallize`, { key: keyOf(ID), body: { keys: [key] } });
      assert.equal(status, 200);
      assert.deepEqual(json?.reports?.map((r) => [r.key, r.outcome]), [[key, 'crystallized']]);
      assert.deepEqual(h.s3.keys(), [`${PREFIX}${key}.mjs`, `${PREFIX}manifest.json`]);

      const crystal = await h.call(`/ep/${ID}/v0/e/${key}`, { key: keyOf(ID), body: { input: { country: 'DE' } } });
      assert.equal(crystal.status, 200);
      assert.equal(crystal.json?.meta?.tier, 'crystal');
      assert.deepEqual(crystal.json?.data, answer);

      const again = await h.call(`/ep/${ID}/v0/crystallize`, { key: keyOf(ID), body: { keys: [key] } });
      assert.deepEqual(again.json?.reports?.map((r) => r.outcome), ['already']);
      assert.equal(h.s3.versions.get(`${PREFIX}manifest.json`)?.length, 1, 'nothing new to publish');
    } finally {
      await h.close();
    }
  });

  test('when another instance publishes first, the report says so and this instance keeps serving without the Crystal', async () => {
    const h = await harness();
    try {
      h.addEndpoint(ID);
      const { key } = await liquidHandler(h);
      // Another instance's Crystallize lands between this one's download and its manifest write.
      const send = h.s3.send.bind(h.s3);
      let hasRaced = false;
      h.s3.send = async (command) => {
        if (!hasRaced && command instanceof PutObjectCommand && command.input.Key === `${PREFIX}manifest.json`) {
          hasRaced = true;
          await send(new PutObjectCommand({ Bucket: BUCKET, Key: command.input.Key, Body: manifestText({}) }));
        }
        return send(command);
      };

      const { status, json } = await h.call(`/ep/${ID}/v0/crystallize`, { key: keyOf(ID), body: { keys: [key] } });
      assert.equal(status, 200);
      const [report] = json?.reports ?? [];
      assert.equal(report?.outcome, 'failed');
      assert.match(report?.reasons.at(-1) ?? '', /another Crystallize finished first, try again/);
      const crystal = await h.call(`/ep/${ID}/v0/e/${key}`, { key: keyOf(ID), body: { input: { country: 'DE' } } });
      assert.equal(crystal.json?.error?.code, 'HANDLER_NOT_FOUND');
    } finally {
      await h.close();
    }
  });
});
