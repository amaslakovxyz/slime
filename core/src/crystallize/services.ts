// The Crystal folder's service methods: one typed function per Crystal, generated
// from manifest.json, that the app calls directly as (connector, input) => data (C10).
// Only the module (sql, params, shape) is model-written; this file is not.
import type { ParamType, ParamTypes } from '../request/params.js';
import type { Shape } from '../request/shape.js';
import type { Manifest } from './manifest.js';

export const SERVICES_FILE = 'services.mjs';
export const SERVICES_TYPES_FILE = 'services.d.mts';

const HEADER = '// Generated by crystallize (@slime-cloud/core). Do not edit: `slime-crystal check` compares it with manifest.json.\n';
const MAX_NAME_WORDS = 6;
const KEY_SUFFIX_LENGTH = 8;
const FALLBACK_NAME = 'crystal';
const WORD = /[A-Za-z0-9]+/g;
const IDENTIFIER = /^[A-Za-z][A-Za-z0-9]*$/;
const NULLABLE_SUFFIX = '|null';
const COMMENT_END = /\*\//g;
// Words a function can't be named; derived names are letters and digits only, so `$`-names never collide.
const RESERVED_WORDS = new Set(
  'await break case catch class const continue debugger default delete do else enum export extends false finally for function if implements import in instanceof interface let new null package private protected public return static super switch this throw true try typeof var void while with yield'.split(' '),
);
const LEAF_TYPES: Readonly<Record<string, string>> = { string: 'string', number: 'number', integer: 'number', boolean: 'boolean', date: 'string', datetime: 'string' };
const PARAM_TYPES: Readonly<Record<ParamType, string>> = { string: 'string', number: 'number', boolean: 'boolean', list: 'Array<string | number | boolean | null>' };
const ANY_PARAM = 'string | number | boolean | Array<string | number | boolean | null>';

/** A readable function name for a new Crystal; names already in the manifest never change. */
export function serviceNameFor(intent: string, key: string, taken: ReadonlySet<string>): string {
  const words = (intent.match(WORD) ?? []).slice(0, MAX_NAME_WORDS);
  const camel = words.map((word, index) => (index === 0 ? word.toLowerCase() : `${word[0]!.toUpperCase()}${word.slice(1).toLowerCase()}`)).join('');
  const name = IDENTIFIER.test(camel) && !RESERVED_WORDS.has(camel) ? camel : FALLBACK_NAME;
  return name === FALLBACK_NAME || taken.has(name) ? `${name}_${key.slice(0, KEY_SUFFIX_LENGTH)}` : name;
}

/** Request key → function name: the manifest's own, or derived for entries made before services existed. */
export function serviceNames({ entries }: Manifest): Map<string, string> {
  const keys = Object.keys(entries).sort();
  const names = new Map(keys.flatMap((key) => (entries[key]!.service ? [[key, entries[key]!.service!] as const] : [])));
  const taken = new Set(names.values());
  for (const key of keys.filter((candidate) => !names.has(candidate))) {
    const name = serviceNameFor(entries[key]!.intent, key, taken);
    names.set(key, name);
    taken.add(name);
  }
  return names;
}

export function renderServices(manifest: Manifest): string {
  const names = serviceNames(manifest);
  const services = [...names].map(([key, name]) => `${docComment(manifest.entries[key]!.intent)}export const ${name} = $service($crystals[${JSON.stringify(key)}]);`);
  return `${HEADER}import { crystalService as $service } from '@slime-cloud/core';\nimport { crystals as $crystals } from './index.mjs';\n\n${services.join('\n\n')}\n`;
}

export function renderServiceTypes(manifest: Manifest): string {
  const names = serviceNames(manifest);
  const declarations = [...names].map(([key, name]) => {
    const { intent, output, paramTypes } = manifest.entries[key]!;
    return `${docComment(intent)}export declare function ${name}(connector: Connector, input${inputIsOptional(paramTypes) ? '?' : ''}: ${inputType(paramTypes)}, options?: CrystalServiceOptions): Promise<${outputType(output)}>;`;
  });
  return `${HEADER}import type { Connector, CrystalServiceOptions } from '@slime-cloud/core';\n\n${declarations.join('\n\n')}\n`;
}

// null means "not given" (R5), so every input is optional and nullable.
function inputType(paramTypes: Readonly<ParamTypes>): string {
  const fields = Object.entries(paramTypes).map(([name, type]) => `${JSON.stringify(name)}?: ${type ? PARAM_TYPES[type] : ANY_PARAM} | null`);
  return fields.length === 0 ? 'Record<string, never>' : `{ ${fields.join('; ')} }`;
}

function inputIsOptional(paramTypes: Readonly<ParamTypes>): boolean {
  return Object.keys(paramTypes).length === 0;
}

// A top-level object is one row, or null when there is none (§4).
function outputType(output: Shape): string {
  const type = shapeType(output);
  return typeof output === 'object' && !Array.isArray(output) ? `${type} | null` : type;
}

function shapeType(shape: Shape): string {
  if (typeof shape === 'string') {
    const isNullable = shape.endsWith(NULLABLE_SUFFIX);
    const leaf = LEAF_TYPES[isNullable ? shape.slice(0, -NULLABLE_SUFFIX.length) : shape] ?? 'unknown';
    return isNullable ? `${leaf} | null` : leaf;
  }
  if (Array.isArray(shape)) return `Array<${shapeType((shape as readonly Shape[])[0]!)}>`;
  const fields = Object.entries(shape).map(([name, child]) => `${JSON.stringify(name)}: ${shapeType(child as Shape)}`);
  return `{ ${fields.join('; ')} }`;
}

function docComment(intent: string): string {
  return `/** ${intent.replace(COMMENT_END, '* /')} */\n`;
}
